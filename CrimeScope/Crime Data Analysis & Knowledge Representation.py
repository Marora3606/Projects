# Question 1f: Confidence Interval
print("\n Question 1f")

if not crime_df.empty:
    counts = crime_df['Location'].value_counts()
    target = counts[(counts >= 200) & (counts <= 500)]

    if not target.empty:
        loc = target.index[0]
        n = target.iloc[0]
        loc_df = crime_df[crime_df['Location'] == loc]
        x = (loc_df['Crime type'] == 'Other theft').sum()
        p_hat = x / n

        z = norm.ppf(0.975)
        se = np.sqrt((p_hat * (1 - p_hat)) / n + 1e-9)
        moe = z * se
        lower, upper = max(0, p_hat - moe), min(1, p_hat + moe)

        print(f"Selected location: '{loc}'")
        print(f"Total reported crimes (n): {n}")
        print(f"Number of 'Other theft' crimes (x): {x}")
        print(f"Sample proportion (p̂): {p_hat:.4f}")
        print(f"95% Confidence Interval: ({lower:.4f}, {upper:.4f})")

        print("\nExplanation for an Expert:")
        print(f"1. To compute the 95% confidence interval for the population proportion π of 'Other theft' crimes, we used the normal approximation to the binomial distribution (sample size n = {n}).")
        print(f"2. The interval was calculated as p̂ ± zα/2 * sqrt[p̂(1−p̂)/n], where p̂ = {p_hat:.4f} and z = {z:.2f}, giving a 95% CI of ({lower:.4f}, {upper:.4f}).")
