import numpy as np

weights = np.array([0.2, 0.4, 0.3, 0.6, 0.2])  # w1..w5

def perceive(x):
    """
    x: array-like of length 5 (numbers)
    Returns 0 if dot(weights,x) < 1 else 1
    """
    x_arr = np.array(x, dtype=float)
    if x_arr.shape[0] != 5:
        raise ValueError("Input must be length 5.")
    s = np.dot(weights, x_arr)
    return 1 if s >= 1.0  else 0
print(perceive([0.2, 0.3, 0.1, 0.5, 0.2]))
