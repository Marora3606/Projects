def query(triples, subject=None, relation=None, object=None):
    """
    Return a list of triples that match the provided pattern.
    None acts as wildcard for subject/predicate/object.
    Example: query(knowledge, subject="Alan Turing") -> returns triples where subject matches.
    """
    results = []
    for (s,r,o) in triples:
        if subject is not None and s != subject:
            continue
        if relation is not None and r != relation:
            continue
        if object is not None and o != object:
            continue
        results.append((s,r,o))
    return results
